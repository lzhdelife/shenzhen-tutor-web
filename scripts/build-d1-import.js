'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { canonicalOrderText } = require('../shared/order-dedupe.js');

function sqlValue(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '0';
  return `'${String(value).replace(/\0/g, '').replace(/'/g, "''")}'`;
}

function jsonValue(value, fallback) {
  return JSON.stringify(value === undefined ? fallback : value);
}

function orderFingerprint(order) {
  const raw = order?.raw || order?.structured?.raw || order?.structured?.rawText || '';
  const canonical = canonicalOrderText(raw);
  return canonical ? crypto.createHash('sha256').update(canonical).digest('hex') : null;
}

function insert(table, columns, values, mode = 'OR IGNORE') {
  return `INSERT ${mode} INTO ${table} (${columns.join(', ')}) VALUES (${values.map(sqlValue).join(', ')});`;
}

function resolvedUserIdSql(user) {
  return `(SELECT id FROM users WHERE id = ${sqlValue(user.id)} OR (role = ${sqlValue(user.role)} AND name = ${sqlValue(user.name || '匿名用户')} AND phone = ${sqlValue(user.phone || '')}) ORDER BY CASE WHEN id = ${sqlValue(user.id)} THEN 0 ELSE 1 END LIMIT 1)`;
}

function buildImportSql(db, options = {}) {
  const users = Array.isArray(db.users) ? db.users : [];
  const orders = Array.isArray(db.orders) ? db.orders : [];
  const feedback = Array.isArray(db.feedback) ? db.feedback : [];
  const userById = new Map(users.map(user => [user.id, user]));
  const referencedUserIds = new Set(orders.map(order => order.agencyId).filter(Boolean));
  for (const order of orders) {
    for (const applicant of Array.isArray(order.applicants) ? order.applicants : []) {
      if (applicant.teacherId) referencedUserIds.add(applicant.teacherId);
    }
  }

  const missingUsers = [...referencedUserIds].filter(id => !userById.has(id));
  if (missingUsers.length) throw new Error(`Orders reference missing users: ${missingUsers.join(', ')}`);

  const generatedAt = options.generatedAt || new Date().toISOString();
  const lines = [
    '-- Generated by scripts/build-d1-import.js.',
    '-- Contains private production data. Do not commit or share this file.',
    'PRAGMA foreign_keys = ON;'
  ];

  for (const id of [...referencedUserIds].sort()) {
    const user = userById.get(id);
    const createdAt = user.createdAt || generatedAt;
    lines.push(insert('users',
      ['id', 'role', 'name', 'phone', 'password_hash', 'preferences_json', 'created_at', 'updated_at'],
      [user.id, user.role, user.name || '匿名用户', user.phone || '', null,
        jsonValue(user.preferences, {}), createdAt, user.updatedAt || createdAt]));
  }

  let importableOrders = 0;
  for (const order of orders) {
    if (!order.id || !order.agencyId) continue;
    const createdAt = order.createdAt || generatedAt;
    const updatedAt = order.updatedAt || createdAt;
    const fingerprint = orderFingerprint(order);
    const structured = { ...order };
    delete structured.sourceImages;
    delete structured.applicants;
    delete structured.importFingerprint;
    const agency = userById.get(order.agencyId);
    const orderValues = [sqlValue(order.id), resolvedUserIdSql(agency), sqlValue(order.source || ''),
      sqlValue(order.status || 'open'), sqlValue(order.district || ''), sqlValue(order.subject || ''),
      sqlValue(order.grade || ''), sqlValue(Number(order.price || 0)), sqlValue(fingerprint),
      sqlValue(jsonValue(structured, {})), sqlValue(createdAt), sqlValue(updatedAt)];
    lines.push(`INSERT OR IGNORE INTO orders (id, agency_id, source, status, district, subject, grade, price, import_fingerprint, structured_json, created_at, updated_at) SELECT ${orderValues.join(', ')} WHERE ${resolvedUserIdSql(agency)} IS NOT NULL;`);

    const locationValues = [order.id, order.place || '', order.address || '', order.placeOriginal || '',
      order.locationVerified ? 1 : 0, order.locationStatus || '', order.locationPoiId || '',
      order.locationCoordinates || '', order.locationAddress || '', order.locationConfidence ?? null,
      order.locationQuery || '', jsonValue(order.locationQueries, []), jsonValue(order.locationCandidates, []),
      jsonValue(order.locationOptions, []), order.locationRelation || '', updatedAt];
    lines.push(`INSERT OR IGNORE INTO order_locations (order_id, place, address, original_place, verified, status, poi_id, coordinates, resolved_address, confidence, query_text, queries_json, candidates_json, options_json, relation, updated_at) SELECT ${locationValues.map(sqlValue).join(', ')} WHERE EXISTS (SELECT 1 FROM orders WHERE id = ${sqlValue(order.id)});`);

    for (const applicant of Array.isArray(order.applicants) ? order.applicants : []) {
      if (!applicant.id || !applicant.teacherId) continue;
      const appliedAt = applicant.createdAt || applicant.at || createdAt;
      const teacher = userById.get(applicant.teacherId);
      const applicationValues = [sqlValue(applicant.id), sqlValue(order.id), resolvedUserIdSql(teacher),
        sqlValue(applicant.name || ''), sqlValue(applicant.phone || ''), sqlValue(applicant.note || ''),
        sqlValue(applicant.status || 'pending'), sqlValue(appliedAt), sqlValue(applicant.updatedAt || appliedAt)];
      lines.push(`INSERT OR IGNORE INTO applications (id, order_id, teacher_id, name, phone, note, status, created_at, updated_at) SELECT ${applicationValues.join(', ')} WHERE EXISTS (SELECT 1 FROM orders WHERE id = ${sqlValue(order.id)}) AND ${resolvedUserIdSql(teacher)} IS NOT NULL;`);
    }
    importableOrders++;
  }

  for (const item of feedback) {
    if (!item.id || !item.content) continue;
    lines.push(insert('feedback', ['id', 'name', 'contact', 'content', 'status', 'created_at'],
      [item.id, item.name || '', item.contact || '', item.content, item.status || 'new', item.createdAt || generatedAt]));
  }

  const announcement = db.announcement;
  if (announcement && announcement.content) {
    const createdAt = announcement.createdAt || generatedAt;
    lines.push(insert('announcements', ['id', 'title', 'content', 'active', 'created_at', 'updated_at'],
      [announcement.id || 'local-announcement', announcement.title || '', announcement.content,
        announcement.active ? 1 : 0, createdAt, announcement.updatedAt || createdAt]));
  }

  for (const key of ['homeAddress', 'maxBikeKm']) {
    if (!(key in (db.settings || {}))) continue;
    lines.push(`INSERT INTO settings (key, value_json, updated_at) VALUES (${sqlValue(key)}, ${sqlValue(jsonValue(db.settings[key], null))}, ${sqlValue(generatedAt)}) ON CONFLICT(key) DO NOTHING;`);
  }

  return {
    sql: `${lines.join('\n')}\n`,
    summary: { users: referencedUserIds.size, orders: importableOrders, feedback: feedback.length }
  };
}

function parseArguments(argv) {
  const values = {};
  for (let index = 0; index < argv.length; index++) {
    const item = argv[index];
    if (!item.startsWith('--')) throw new Error(`Unexpected argument: ${item}`);
    const name = item.slice(2);
    const value = argv[++index];
    if (!value || value.startsWith('--')) throw new Error(`Missing value for --${name}`);
    values[name] = value;
  }
  return values;
}

function main() {
  const args = parseArguments(process.argv.slice(2));
  const input = path.resolve(args.input || path.join(__dirname, '../TutorPlatform/data/db.json'));
  if (!args.output) throw new Error('Pass --output <temporary-path>. The generated SQL contains private data.');
  const output = path.resolve(args.output);
  if (input === output) throw new Error('Input and output paths must be different.');
  const db = JSON.parse(fs.readFileSync(input, 'utf8'));
  const result = buildImportSql(db);
  fs.writeFileSync(output, result.sql, { encoding: 'utf8', mode: 0o600 });
  console.log(JSON.stringify({ output, ...result.summary }, null, 2));
}

if (require.main === module) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { buildImportSql, orderFingerprint, resolvedUserIdSql, sqlValue };
